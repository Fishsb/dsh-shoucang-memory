const targets = [
  { path: join(root, 'src', 'criteria.generated.ts'), text: buildTs() },
  { path: join(root, 'skill', 'engine', 'criteria.md'), text: buildMd() },
  { path: join(root, 'skill', 'engine', 'criteria-gate.json'), text: buildGate() },
]

let stale = 0
for (const t of targets) {
  const cur = existsSync(t.path) ? readFileSync(t.path, 'utf8') : null
  if (cur === t.text) { if (!CHECK) console.log(`✓ 最新 ${t.path.replace(root + '\\', '').replace(root + '/', '')}`); continue }
  if (CHECK) { stale++; console.log(`⛔ 投影过期：${t.path}（重跑 node scripts/gen-criteria.mjs）`); continue }
  writeFileSync(t.path, t.text, 'utf8')
  console.log(`✎ 生成 ${t.path.replace(root + '\\', '').replace(root + '/', '')}（${t.text.length} 字节）`)
}
if (CHECK && stale) { console.error(`\nFAIL：${stale} 处投影与注册表不一致`); process.exit(1) }
if (CHECK) console.log('PASS：五处投影与注册表一致（A TS / B 判据表 / C 脚本参数）')
