#!/usr/bin/env node
// gen-criteria.mjs — 判据投影生成器（ADR-122「记忆核心 v2」）
//
// 唯一事实源 = skill/engine/criteria.json。禁止手写下列投影；改判据一律「改注册表 → 重跑本器 → 过机检门」。
//   A src/criteria.generated.ts   —— TS 投影（两个 prompt 的判据段 / judgement 提示 / L0·GATE·HEALTH·SURFACE 常量）
//   B skill/engine/criteria.md    —— 人读判据表（spec / contract 引用它，不再各自复述）
//   C skill/engine/criteria-gate.json —— 脚本面扁平参数（write_gate / health_check 读它）
// 用法: node scripts/gen-criteria.mjs [--check]    # --check：只校验投影是否最新（exit 1 = 需重跑）
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const regPath = join(root, 'skill', 'engine', 'criteria.json')
const reg = JSON.parse(readFileSync(regPath, 'utf8'))
const CHECK = process.argv.includes('--check')

/** A · TS 投影 */
const buildTs = () => {
  const lines = []
  lines.push('// AUTO-GENERATED by scripts/gen-criteria.mjs from skill/engine/criteria.json — DO NOT EDIT.')
  lines.push('// 判据唯一事实源 = skill/engine/criteria.json；改判据请改注册表后重跑生成器（scripts/check-criteria.mjs 机检一致）。')
  lines.push('')
  lines.push(`export const CRITERIA_VERSION = ${JSON.stringify(reg.version)}`)
  lines.push('')
  lines.push('/** 摄取域判据段（拼进 DEFAULT_DISTILL_PROMPT） */')
  lines.push('export const INGEST_JUDGE = [')
  for (const l of reg.ingest.judgeText) lines.push(`  ${JSON.stringify(l)},`)
  lines.push("].join('\\n')")
  lines.push('')
  lines.push('/** 巩固域判据段（拼进 DEEP_SLEEP_PROMPT） */')
  lines.push('export const CONSOLIDATE_JUDGE = [')
  for (const l of reg.consolidate.judgeText) lines.push(`  ${JSON.stringify(l)},`)
  lines.push("].join('\\n')")
  lines.push('')
  lines.push(`export const JUDGEMENT_HINT = ${JSON.stringify(reg.judgement.hint)}`)
  lines.push(`export const LEDGER_FILE = ${JSON.stringify(reg.judgement.ledger)}`)
  lines.push('')
  for (const [name, val] of [['L0', reg.l0], ['GATE', reg.gate], ['HEALTH', reg.health], ['SURFACE', reg.surface]]) {
    lines.push(`export const ${name} = ${JSON.stringify(val, null, 2)} as const`)
    lines.push('')
  }
  lines.push(`export const CRITERIA_ROWS = ${JSON.stringify([...reg.ingest.criteria, ...reg.consolidate.criteria].map((c) => ({ id: c.id, domain: c.id.split('.')[0], kind: c.kind, text: c.text, params: c.params })), null, 2)} as const`)
  lines.push('')
  return lines.join('\n')
}

/** B · 人读判据表 */
const buildMd = () => {
  const o = []
  o.push('<!-- AUTO-GENERATED by scripts/gen-criteria.mjs from skill/engine/criteria.json — DO NOT EDIT -->')
  o.push('# 判据注册表（投影 · 人读）')
  o.push('')
  o.push(`> 唯一事实源 = \`skill/engine/criteria.json\`（${reg.version}）。本表由生成器产出；spec / distill-contract 只**引用**本表，不再各自复述判据。`)
  o.push('> 机检：`node scripts/check-criteria.mjs`（纳入 `npm test`）——投影与注册表不一致即失败。')
  o.push('')
  o.push('## L0 共用内核（两域同口径，枚举不打分）')
  o.push('')
  o.push('| 维度 | 取值 |')
  o.push('|---|---|')
  for (const [k, v] of Object.entries(reg.l0)) o.push(`| ${k} | ${v.values.join(' · ')} |`)
  o.push('')
  for (const [key, dom] of [['ingest', reg.ingest], ['consolidate', reg.consolidate]]) {
    o.push(`## L1 · ${dom.label}（domain=\`${dom.domain}\`）`)
    o.push('')
    o.push('| 判据 id | 强制 | 内容 | 参数 |')
    o.push('|---|---|---|---|')
    for (const c of dom.criteria) o.push(`| \`${c.id}\` | ${c.kind} | ${c.text} | \`${JSON.stringify(c.params)}\` |`)
    o.push('')
  }
  o.push('## 硬门与观测参数')
  o.push('')
  o.push('| 面 | 参数 |')
  o.push('|---|---|')
  o.push(`| 写门容量 | ${Object.entries(reg.gate.caps).map(([k, v]) => `${k}≤${v}`).join(' · ')}（env: ${Object.values(reg.gate.envOverride).join(' / ')}） |`)
  o.push(`| 写门退出码 | 容量=${reg.gate.exit.capacity} · 指针=${reg.gate.exit.pointer} · 格式=${reg.gate.exit.format} |`)
  o.push(`| 体检 | R=${reg.health.R} · K=${reg.health.K} · notes 警戒=${reg.health.notesWarn} · 检查项=${reg.health.checks.join('/')} |`)
  o.push(`| 注入 | ≤${reg.surface.injection.budgetChars} 字符 · order=${reg.surface.injection.order} · 相关性=${reg.surface.injection.relevance} · 新鲜度槽=${reg.surface.injection.freshSlots} |`)
  o.push(`| 召回 | topK=${reg.surface.recall.topK}(≤${reg.surface.recall.topKMax}) · scope=${reg.surface.recall.scope} · cold 降权=${reg.surface.recall.coldFactorPercent}% |`)
  o.push(`| 融合 | ${reg.surface.fusion.kind}（k=${reg.surface.fusion.k}）· 回退=${reg.surface.fusion.fallback}${reg.surface.fusion.weights ? `（dense ${reg.surface.fusion.weights.dense}/lex ${reg.surface.fusion.weights.lexical}）` : ''} · 同 § 抑制=${reg.surface.fusion.dedupBySection} |`)
  o.push(`| 阈值 | ${reg.surface.threshold.metric} · T_on=${reg.surface.threshold.tOn} / T_off=${reg.surface.threshold.tOff} |`)
  o.push(`| rerank | enabled=${reg.surface.rerank.enabled} · 触发门：索引行>${reg.surface.rerank.gate.indexRows} 或跟读率连续 ${reg.surface.rerank.gate.followRateDropRuns} 次下降 |`)
  o.push(`| MCL | 熟悉度阈值=${reg.surface.mcl.familiarThreshold} · maxNudges=${reg.surface.mcl.maxNudges} · 材料预算=${reg.surface.mcl.budgetChars} · 指针=${reg.surface.mcl.topK} |`)
  o.push(`| judgement | ingest=[${reg.judgement.fields.ingest.join(',')}] · consolidate=[${reg.judgement.fields.consolidate.join(',')}] · 台账=${reg.judgement.ledger} |`)
  o.push('')
  o.push('## 明确不做（anti-scope）')
  o.push('')
  for (const a of reg.antiScope) o.push(`- ${a}`)
  o.push('')
  return o.join('\n')
}

/** C · 脚本面扁平参数 */
const buildGate = () => JSON.stringify({
  version: reg.version,
  caps: reg.gate.caps,
  envOverride: reg.gate.envOverride,
  notesWarn: reg.gate.notesWarn,
  exit: reg.gate.exit,
  R: reg.health.R,
  K: reg.health.K,
  granularity: { R: reg.ingest.criteria.find((c) => c.id === 'ingest.granularity.split-law').params.R, K: reg.ingest.criteria.find((c) => c.id === 'ingest.granularity.split-law').params.K },
  dedup: reg.ingest.criteria.find((c) => c.id === 'ingest.dedup.bigram').params,
  format: reg.ingest.criteria.find((c) => c.id === 'ingest.format.index-line').params,
  demote: reg.consolidate.criteria.find((c) => c.id === 'consolidate.demote.archive').params,
  surface: reg.surface,
  health: reg.health,
}, null, 2) + '\n'

const targets = [
  { path: join(root, 'src', 'criteria.generated.ts'), text: buildTs() },
  { path: join(root, 'skill', 'engine', 'criteria.md'), text: buildMd() },
  { path: join(root, 'skill', 'engine', 'criteria-gate.json'), text: buildGate() },
]

let stale = 0
for (const t of targets) {
  const cur = existsSync(t.path) ? readFileSync(t.path, 'utf8') : null
  if (cur === t.text) { if (!CHECK) console.log(`✓ 最新 ${t.path.replace(root + '\\', '').replace(root + '/', '')}`); continue }
  if (CHECK) { stale++; console.log(`⛔ 投影过期：${t.path}（重跑 node scripts/gen-criteria.mjs）`); continue }
  writeFileSync(t.path, t.text, 'utf8')
  console.log(`✎ 生成 ${t.path.replace(root + '\\', '').replace(root + '/', '')}（${t.text.length} 字节）`)
}
if (CHECK && stale) { console.error(`\nFAIL：${stale} 处投影与注册表不一致`); process.exit(1) }
if (CHECK) console.log('PASS：五处投影与注册表一致（A TS / B 判据表 / C 脚本参数）')
